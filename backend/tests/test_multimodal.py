# ── tts ──────────────────────────────────────────────────────────────────────

def test_tts_writes_audio_and_reports_metadata(workspace, monkeypatch):
    async def fake_synth(text, *, model=None, voice=None, response_format="mp3"):
        return b"ID3-audio-bytes"

    monkeypatch.setattr(speech_service, "synthesize", fake_synth)
    out = asyncio.run(multimodal._exec_tts({"text": "ciao", "voice": "nova"}, None))

    assert out["path"].endswith(".mp3")
    assert out["bytes"] == len(b"ID3-audio-bytes")
    assert out["voice"] == "nova"
    assert out["chars"] == 4
    assert (workspace / out["path"]).read_bytes() == b"ID3-audio-bytes"


def test_tts_format_drives_the_extension(workspace, monkeypatch):
    async def fake_synth(text, *, model=None, voice=None, response_format="mp3"):
        assert response_format == "wav"
        return b"RIFF"

    monkeypatch.setattr(speech_service, "synthesize", fake_synth)
    out = asyncio.run(multimodal._exec_tts({"text": "hi", "format": "wav"}, None))
    assert out["path"].endswith(".wav") and out["format"] == "wav"


def test_tts_rejects_an_unknown_format(workspace):
    with pytest.raises(ValueError, match="unsupported format"):
        asyncio.run(multimodal._exec_tts({"text": "hi", "format": "exe"}, None))


def test_tts_requires_text(workspace):
    with pytest.raises(ValueError, match="'text' is required"):
        asyncio.run(multimodal._exec_tts({}, None))


def test_tts_surfaces_a_provider_error_as_a_node_failure(workspace, monkeypatch):
    async def boom(text, **kwargs):
        raise speech_service.SpeechError("no TTS model configured")

    monkeypatch.setattr(speech_service, "synthesize", boom)
    with pytest.raises(RuntimeError, match="no TTS model configured"):
        asyncio.run(multimodal._exec_tts({"text": "hi"}, None))
