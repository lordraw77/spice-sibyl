# ── image.generate ───────────────────────────────────────────────────────────

def test_image_generate_writes_the_file_and_reports_the_path(workspace, monkeypatch):
    async def fake_generate(prompt, width=1024, height=1024, provider=None):
        return {"b64_json": base64.b64encode(_PNG).decode(), "provider": "gemini", "model": "m"}

    monkeypatch.setattr(image_service, "generate_image", fake_generate)
    out = asyncio.run(multimodal._exec_image_generate({"prompt": "a cat"}, None))

    assert out["path"].startswith("generated/") and out["path"].endswith(".png")
    assert out["bytes"] == len(_PNG)
    assert out["provider"] == "gemini"
    # The bytes go to disk, not into the output: the run log must stay readable.
    assert "b64_json" not in out
    assert (workspace / out["path"]).read_bytes() == _PNG


def test_image_generate_honours_an_explicit_path(workspace, monkeypatch):
    async def fake_generate(prompt, **kwargs):
        return {"b64_json": base64.b64encode(_PNG).decode(), "provider": "p", "model": "m"}

    monkeypatch.setattr(image_service, "generate_image", fake_generate)
    out = asyncio.run(multimodal._exec_image_generate(
        {"prompt": "x", "path": "art/cat.png"}, None))
    assert out["path"] == "art/cat.png"
    assert (workspace / "art" / "cat.png").is_file(), "nested output dirs must be created"


