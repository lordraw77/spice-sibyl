# ── image.ocr ────────────────────────────────────────────────────────────────

def test_image_ocr_sends_the_image_as_a_data_uri(workspace, monkeypatch):
    (workspace / "shot.png").write_bytes(_PNG)
    captured = {}

    async def fake_complete(request):
        captured["request"] = request
        return {"choices": [{"message": {"content": "INVOICE 42\n"}}], "usage": {}}, "miss"

    monkeypatch.setattr("app.workflow.nodes.llm._cached_complete", fake_complete)
    out = asyncio.run(multimodal._exec_image_ocr(None, "default", {"path": "shot.png"}, None))

    assert out["text"] == "INVOICE 42"
    assert out["chars"] == len("INVOICE 42")
    parts = captured["request"].messages[0].content
    assert isinstance(parts, list), "the vision call must send multimodal content parts"
    assert parts[1]["image_url"]["url"].startswith("data:image/png;base64,")


def test_image_ocr_prompt_can_be_overridden(workspace, monkeypatch):
    (workspace / "shot.png").write_bytes(_PNG)
    captured = {}

    async def fake_complete(request):
        captured["request"] = request
